@Composable
expect fun LiquidGlassAppBottomNavigationBar(
    startDestination: Any = HomeDestination,
    navController: NavController,
    backdrop: PlatformBackdrop,
    viewModel: SharedViewModel,
    isScrolledToTop: Boolean = false,
    showAnalyticsTab: Boolean = false,
    showMixForYouTab: Boolean = false,
    onOpenNowPlaying: () -> Unit = {},
    // False draws the same folding bar in the flat material (liquid glass turned off).
    liquidGlass: Boolean = true,
    reloadDestinationIfNeeded: (KClass<*>) -> Unit = { _ -> },
)

sealed class BottomNavScreen(
    val ordinal: Int,
    val destination: Any,
    val title: StringResource,
    val icon: @Composable () -> Unit,
) {
    data object Home : BottomNavScreen(
        ordinal = 0,
        destination = HomeDestination,
        title = Res.string.home,
        icon = {
            Icon(
                SimpIcons.Home,
                contentDescription = null,
            )
        },
    )

    data object Search : BottomNavScreen(
        ordinal = 1,
        destination = SearchDestination,
        title = Res.string.search,
        icon = {
            Icon(
                SimpIcons.Search,
                contentDescription = null,
            )
        },
    )

    data object Library : BottomNavScreen(
        ordinal = 2,
        destination = LibraryDestination,
        title = Res.string.library,
        icon = {
            Icon(
                imageVector = SimpIcons.LibraryMusic,
                contentDescription = null,
            )
        },
    )

    data object Account : BottomNavScreen(
        ordinal = 3,
        destination = LoginDestination,
        title = Res.string.home,
        icon = { Icon(SimpIcons.Person, contentDescription = "Account") },
    )

    data object Settings : BottomNavScreen(
        ordinal = 4,
        destination = SettingsDestination,
        title = Res.string.home,
        icon = { Icon(SimpIcons.Settings, contentDescription = "Settings") },
    )

    data object Room : BottomNavScreen(
        ordinal = 6,
        destination = ListenTogetherDestination,
        title = Res.string.home,
        icon = { Icon(SimpIcons.Groups, contentDescription = "Room") },
    )
}